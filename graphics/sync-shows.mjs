// Brings the client tier's graphics into the bundle: node sync-shows.mjs
//
// A show keeps its own Remotion components in shows/<id>/graphics/ (outside the
// engine's git, see caption_engine/shows.py). The bundler only compiles what is
// under src/ and resolves `remotion` from this folder's node_modules, so each
// show's folder is copied to src/<id>/ (gitignored), its fonts to public/fonts/,
// and src/_shows.ts is written to register what they export:
//
//   shows/<id>/graphics/index.ts   export const TEMPLATES: Record<string, FC>
//                                  export const COMPOSITIONS?: CompositionProps[]
//
// Copied to src/<id>/ rather than src/_shows/<id>/ so an episode's scenes keep
// importing "../<id>/scene" from src/_episode/.
//
// Files are only written when their bytes change: a bundle running while
// another render syncs must not see a file rewritten under it. render.mjs runs
// this before every bundle; `npm run studio` does too.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// The engine's own folders under src/; a show with one of these ids is refused.
const RESERVED = new Set(["templates", "panel", "_episode", "_shows"]);

export function showsRoot() {
  return process.env.CAPTIONEER_SHOWS ?? path.join(here, "..", "shows");
}

const same = (a, b) => existsSync(b) && readFileSync(a).equals(readFileSync(b));

function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, "utf8") === text) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

function mirror(src, dst) {
  mkdirSync(dst, { recursive: true });
  const want = new Set(readdirSync(src));
  for (const name of readdirSync(dst)) {
    if (!want.has(name)) rmSync(path.join(dst, name), { recursive: true, force: true });
  }
  for (const name of want) {
    const s = path.join(src, name), d = path.join(dst, name);
    if (statSync(s).isDirectory()) mirror(s, d);
    else if (!same(s, d)) copyFileSync(s, d);
  }
}

function copyFonts(dir, dst) {
  if (!existsSync(dir)) return;
  mkdirSync(dst, { recursive: true });
  for (const name of readdirSync(dir)) {
    const s = path.join(dir, name);
    if (statSync(s).isFile() && !same(s, path.join(dst, name))) copyFileSync(s, path.join(dst, name));
  }
}

export function syncShows() {
  const root = showsRoot();
  const synced = [];
  if (existsSync(root)) {
    copyFonts(path.join(root, "_shared", "fonts", "graphics"), path.join(here, "public", "fonts"));
    for (const id of readdirSync(root).sort()) {
      const dir = path.join(root, id);
      if (id.startsWith("_") || id.startsWith(".") || !statSync(dir).isDirectory()) continue;
      copyFonts(path.join(dir, "fonts", "graphics"), path.join(here, "public", "fonts"));
      const g = path.join(dir, "graphics");
      if (!existsSync(g)) continue;
      if (RESERVED.has(id) || !/^[a-z][a-z0-9_-]*$/.test(id)) throw new Error(`show id ${JSON.stringify(id)} can't be a folder under src/`);
      mirror(g, path.join(here, "src", id));
      if (existsSync(path.join(g, "index.ts"))) synced.push(id);
    }
  }
  const ident = (id) => "show_" + id.replace(/-/g, "_");
  writeIfChanged(path.join(here, "src", "_shows.ts"),
    "// Generated by sync-shows.mjs from the shows folder. Do not edit.\n" +
    'import type { CompositionProps } from "remotion";\n' +
    'import type React from "react";\n' +
    synced.map((id) => `import * as ${ident(id)} from "./${id}";\n`).join("") +
    "\n// eslint-disable-next-line @typescript-eslint/no-explicit-any\n" +
    "export const SHOW_TEMPLATES: Record<string, React.FC<any>> = {\n" +
    synced.map((id) => `  ...${ident(id)}.TEMPLATES,\n`).join("") +
    "};\n\n" +
    "// eslint-disable-next-line @typescript-eslint/no-explicit-any\n" +
    "export const SHOW_COMPOSITIONS: CompositionProps<any, any>[] = [\n" +
    synced.map((id) => `  ...((${ident(id)} as any).COMPOSITIONS ?? []),\n`).join("") +
    "];\n");
  return synced;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const ids = syncShows();
  process.stderr.write(`synced shows: ${ids.join(", ") || "(none)"}\n`);
}
